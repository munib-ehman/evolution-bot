import assert from 'node:assert/strict';
import { build } from 'esbuild';

const values = new Map();
const sessions = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
globalThis.sessionStorage = { getItem: key => sessions.get(key) ?? null, setItem: (key, value) => sessions.set(key, value), removeItem: key => sessions.delete(key) };
const bundle = await build({ entryPoints: ['src/network/analytics.ts'], bundle: true, platform: 'node', format: 'esm', write: false, define: { 'import.meta.env': '{}' } });
const analytics = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
assert.equal(analytics.consent(), null);
analytics.track('feed_view');
assert.equal(analytics.localEvents().length, 0);
assert.equal(values.size, 0);
analytics.setConsent(true);
analytics.track('feed_view');
analytics.track('feed_view');
analytics.track('post_view', 'post-one');
analytics.track('post_view', 'post-one');
analytics.track('post_view', 'post-two');
const flow = crypto.randomUUID();
analytics.track('post_open', null, flow);
analytics.track('form_start', null, flow);
analytics.track('publish_attempt', null, flow);
analytics.track('publish_success', 'post-one', flow);
analytics.track('checkout_click', 'post-one');
let report = await analytics.readReport();
assert.equal(report.counts.find(row => row.name === 'feed_view').total, 1);
assert.equal(report.counts.find(row => row.name === 'post_view').total, 2);
assert.equal(report.counts.find(row => row.name === 'checkout_click').total, 1);
assert.equal(report.counts.find(row => row.name === 'publish_success').total, 1);
assert(analytics.localEvents().filter(row => row.flowId === flow).length === 4);
assert.equal(new Set(analytics.localEvents().map(row => row.visitorId)).size, 1);
const now = Date.now;
Date.now = () => now() + 31 * 60 * 1000;
analytics.track('feed_view');
Date.now = now;
assert.equal(new Set(analytics.localEvents().map(row => row.sessionId)).size, 2);
analytics.track('not_allowed');
assert(!analytics.localEvents().some(row => row.name === 'not_allowed'));
analytics.setConsent(false);
assert.equal(analytics.consent(), false);
assert.equal(analytics.localEvents().length, 0);
assert(!values.has('evolution:analytics:visitor'));
analytics.track('checkout_click', 'post-one');
assert.equal(analytics.localEvents().length, 0);
globalThis.localStorage = { getItem() { throw Error('blocked'); }, setItem() { throw Error('blocked'); }, removeItem() { throw Error('blocked'); } };
analytics.setConsent(true);
analytics.track('feed_view');
assert.equal(analytics.localEvents().length, 1);
for (let index = 0; index < 1005; index++) analytics.track('post_open');
assert.equal(analytics.localEvents().length, 1000);
await analytics.flushEvents();
console.log('PASS: no tracking before opt-in, consent withdrawal, bounded local history, session deduplication, posting flow attribution, event allowlist and blocked-storage resilience.');
