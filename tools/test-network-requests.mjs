import assert from 'node:assert/strict';
import fs from 'node:fs';
import postcss from 'postcss';
import { build } from 'esbuild';
import { validateRequest, requestPost } from '../src/network/requests.mjs';
import { matchingPosts } from '../src/network/topics.mjs';
import { canHire } from '../src/network/model.mjs';

const draft = { title: 'Ten relevant companies with source links', owner: 'Buyer', text: 'Find sourced market research for a new product. Return ten relevant companies with source links and a short summary.', budget: '150', category: 'Research', responseUrl: 'https://example.com/contact' };
const requestUi = fs.readFileSync('src/network/main.tsx', 'utf8');
for (const copy of ['Post the outcome. Find an agent to get it done.', 'What outcome do you want?', 'What does done look like?', 'Desired outcome', 'What outcome does it deliver?']) assert(requestUi.includes(copy));
assert(requestUi.includes('name="title" required maxLength={100}'));
assert(requestUi.includes('name="text" required minLength={80} maxLength={600}'));
postcss.parse(fs.readFileSync('src/network/dark.css', 'utf8'));
for (const page of ['index', 'app']) assert(fs.readFileSync('versions/network/' + page + '.html', 'utf8').includes('data-theme="dark"'));
assert.equal(validateRequest(draft).title, draft.title);
assert.equal(validateRequest(draft).budget, 150);
for (const budget of [undefined, '', 0, -1, 'not a number', Infinity, 1000001, 1.001]) assert.throws(() => validateRequest({ ...draft, budget }));
for (const size of [79, 601]) assert.throws(() => validateRequest({ ...draft, text: 'a'.repeat(size) }));
for (const size of [80, 600]) assert.equal(validateRequest({ ...draft, text: 'a'.repeat(size) }).text.length, size);
const legacy = requestPost({ ...draft, budget: null, text: 'a'.repeat(1000) });
assert.equal(legacy.budget, null);
assert.equal(legacy.text.length, 1000);
for (const change of [{ title: '' }, { owner: '' }, { text: '' }, { category: 'Unknown' }, { responseUrl: 'javascript:alert(1)' }, { responseUrl: 'https://user:pass@example.com' }]) assert.throws(() => validateRequest({ ...draft, ...change }));
const post = requestPost(draft);
assert.equal(post.kind, 'request');
assert.equal(canHire(post), false);
assert.equal(matchingPosts([post], ['Research', 'Sales', 'Writing']).length, 1);
const bundle = await build({ entryPoints: ['src/network/store.ts'], bundle: true, platform: 'node', format: 'esm', write: false, define: { 'import.meta.env': '{}' } });
const store = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const values = new Map();
globalThis.localStorage = { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
let confirmed;
await store.publishRequest(draft, id => { confirmed = id; });
assert.equal((await store.readFeed())[0].id, confirmed);
assert.equal((await store.readFeed())[0].responseUrl, draft.responseUrl);
assert.equal((await store.readFeed())[0].budget, 150);
assert.deepEqual(await store.ownAgents(null), []);
await assert.rejects(store.publishRequest({ ...draft, text: '' }));
assert.equal((await store.readFeed()).length, 1);
console.log('PASS: request validation, safe response links, matching topics, persisted requests, publication callback and no agent/hire confusion.');
